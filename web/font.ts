export const GLYPH_W = 5;
/** advance per character, glyph plus one column of space */
export const ADVANCE = 6;
/** rows above the cap line, for accents on capitals */
export const ABOVE = 2;
/** rows from the cap line down: cap height 7, two descender rows */
export const BELOW = 9;

const rows = (g: string) => (g ? g.split("/") : []);

/** The pixels of one character as [x, y] with y from the cap line (negative above it); unknown characters draw "?". */
export function glyph(ch: string): [number, number][] {
  const out: [number, number][] = [];
  const put = (g: string, dy: number) => rows(g).forEach((r, y) => [...r].forEach((p, x) => { if (p === "#") out.push([x, y + dy]); }));
  const acc = ACCENTED[ch];
  if (acc) {
    const [base, mark] = acc;
    put(G[base], 0);
    put(MARK[mark], base === base.toUpperCase() && base !== "ı" ? -ABOVE : 0);
  } else put(G[ch] ?? G["?"], 0);
  return out;
}

/** Whether the font draws a character itself rather than falling back to "?". */
export const hasGlyph = (ch: string) => ch in G || ch in ACCENTED;

const CACHE = new Map<string, HTMLCanvasElement>();
/**
 * A line of text at one source pixel per font pixel, in a colour: ADVANCE * length - 1 wide and ABOVE + BELOW tall,
 * the cap line ABOVE rows down. Cached, so a label is drawn once and stamped every frame.
 */
export function textSprite(text: string, color: string): HTMLCanvasElement {
  const key = `${color}\u0000${text}`;
  let c = CACHE.get(key);
  if (c) return c;
  const chars = [...text];
  c = document.createElement("canvas");
  c.width = Math.max(1, chars.length * ADVANCE - 1);
  c.height = ABOVE + BELOW;
  const g = c.getContext("2d")!;
  g.fillStyle = color;
  chars.forEach((ch, i) => { for (const [x, y] of glyph(ch)) g.fillRect(i * ADVANCE + x, ABOVE + y, 1, 1); });
  if (CACHE.size > 500) CACHE.clear(); // labels change rarely; this only bounds a long session
  CACHE.set(key, c);
  return c;
}
